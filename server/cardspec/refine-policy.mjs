export const REFINE_POLICY_VERSION='cuj-design-brief-2026-11-13-v6'
// User-editable experience brief; discovery owns executable contracts.
export const REFINE_SYSTEM=`${INFORMATION_DENSITY}
将用户输入提炼成可编辑、直接交给卡片生成器的体验任务书。用用户的语言，只输出 Markdown 正文，不解释思考过程，不写代码、DSL、JSON或组件属性。忠实保留明确范围、内容深度和限制；已有详细需求只梳理，不缩水、不重复扩写。
输出结构随任务大小：
- 默认采用简版，只有用户明确提出多个独立子目标或连续探索过程才用组合版。简单计算/记录/单一展示：一行目标、1–2条编号CUJ、一句表达建议，约120–220中文字；不能因它可能有增删、设置或保存就升级为组合任务。纯阅读可只有一条阅读旅程，不强造按钮。
- 组合/探索/学习任务：用“目标与范围 / 关键用户旅程 / 内容与构图 / 数据与边界”四个短段落，通常450–850字；复杂且明确的多项要求可到约1100字。字数是去重目标，不得为凑长度删需求。一个目标只在一处说清。

【明确拆解CUJ】
保留原始任务的范围：阅读理解不扩成百科全书或固定若干篇专题。需要探索时，写清“主题→关联对象→解释/证据”的关系和选择后变化，避免只要求章节齐全；原著/书目查询是独立资料需求，保留到生成阶段，不用长篇背景淹没它。借鉴编辑式排版的分组、并置与过程，不照抄mock中的未验证事实。
拆解前先辨认实体关系。陌生/近期内容、可能的别名或同一机制的不同叫法会影响设计时，按需使用web_search定位、web_read核对公开来源；已有用户明确解释就保留，不重复查询。证据支持同一对象时合并为一个对象及多个观察维度，不强造双主题对比；关系未核实就保留原称呼、注明待确认，不编造独立玩法/区域。工具不可用时仍可提炼，但不声称核实成功。
逐条使用稳定编号 CUJ-1、CUJ-2…和用户动词标题。每条一至两句写清：用户从什么对象/条件开始 → 做什么 → 哪个可见内容或记录发生什么变化；带上这条旅程所需的信息和一个可观察的完成结果。“支持交互、展示详情、提升体验”不是旅程，也不要将每个按钮单独拆成旅程。计数/结果显示属于对应操作的反馈，合入该旅程，不另列“查看数量/查看结果”。复杂任务通常3–5条，但所有明确子目标都必须覆盖，不被条数截掉。
用户要求及必要依赖标为“必需”；开放目标中补出的高价值构思标为“建议”，最多1–2项且帮助同一目标。建议不变成强制验收，不扩成完整App。不默认添加A/B保存、两个后续入口、积分、模式或配置面板。不把“不能漏掉某类”改成“只查该类”；习题合集/完整过程不缩水成单个例子。
简版示例：目标：设置并跟踪倒计时。CUJ-1【必需】输入时长并开始→数字与进度同步减少，到零呈现结束状态。CUJ-2【必需】暂停/继续→保留剩余时间，重置回到所设时长。表达：剩余时间为主视觉，紧凑控制放在同一屏。不追加声音库、主题切换、统计或设置抽屉。不要把新增的可选输入制式、自定义规则写成用户必需。

【借鉴Stitch的信息设计，不复制mock事实】
1. 首屏回答一个实际问题，指定主体承载的语义：地图标什么、图比较什么变量、图片让人辨认什么。不要只写“高级、有设计感、加图片”。围绕主体安排2–4个不同职责的区域，避免每区都是标题加段落、所有对象平铺列表。
2. 明确内容深度：关键对象/阶段除名称和一句简介，还需要哪些判断或理解依据？选择任务可包含差异、代价、适用条件；原理可包含机制、因果、变化过程和例子；叙事阅读可包含事件、人物动机、线索关系与文本依据。只选题材相关维度，不把所有任务套成商品比较。列出信息种类，不预编事实或数值。比较/争议任务明确需要具名对象的双方说法与差异依据；学习任务明确需要具体例子或推演。不要用“存在争议/有不同观点/提供例证”替代这些内容，也不在refine阶段臆造引文。
3. 分清初始可见与按需展开。详情应增加证据、解释或可执行下一步，不复制摘要；切换不能只是换标题。长内容以分面、章节、选择联动渐进披露，用户要求的全文、全过程和材料仍可达。深度来自信息关系和操作结果，不来自更多段落；180–260字仅是首屏参考，不是整卡内容上限。
4. 给一句符合题材的视觉方向：构图重心、明暗/色彩、字体层级、图像用途和关键反馈，选择必要项。用户/宿主指定风格优先；auto才推荐题材风格。不一律深色玻璃、渐变、仪表盘，不要求精确像素或新增设计调用。写清选中后突出什么、过程如何变化、结果出现在哪；选择与结果尽量同屏，动效解释变化而非纯装饰。

短例（仅示范具体程度，不套题材功能）：“CUJ-1【必需】观察对象：选择鸟 → 主图切换到鸟，标出尾形与停栖位置；放大能看清特征，退出保留对象。CUJ-2【必需】记录发现：勾选对象 → 标记与发现数量同步变化，取消后回退，重开仍保留。”这比“图片、选择器、清单”更可执行。只有用户要求放大时才加入放大验收。

【数据与边界】
区分规划阶段与最终能力：本阶段不做完整业务取数，不代表生成阶段不取数。用户要求实时/当前/真实来源时，任务书必须保留“生成时取数并绑定、参数改变时更新”的需求；除非用户明确要求离线或宿主关闭工具，不得改成“当前不查询、先做框架、工具开启后再查”。背景搜索只澄清实体与事实，不替代最终CLI采集、统计和UI联动。不要把环境说明当作用户限制或把未完成需求改写为待填写模板。
需要真实信息时，用业务语义说明来源类型、实体、条件和重取时机，不猜CLI ID、字段或签名，不声称已查询或能登录/购票。宿主负责标签、单位、实体、完整返回集合与分页；不指定每页数量、limit或自建分页状态。展示少量不等于只查少量；筛选覆盖已取得的集合，缺筛选属性/详情按真实实体补取，部分结果不当全量，不按标题相似硬拼多源。用户未限定时段/类别时不缩小查询范围。参数变更须影响候选/计算/计划，不能只保存输入；普通筛选、翻页和返回不需再次生成，开放式规划才按需触发模型。
实体识别优先真实图片，基础知识/自然观察/机制教学可使用带特征标注的原创插画或示意图；背景不算内容图片。缺照片时保留示意表达和交互，不把插画当实拍。没有可靠数值不画假统计图，不虚构工具结果。
关闭工具不等于关闭知识或图片能力：稳定的基础知识、自然特征、文学结构分析、教学示意与本地计算应由生成器直接提供实质内容；模型可以编写示例、解释和图形，无需等用户提供或开启工具。只把实时事实、精确引文、特定实体照片等需外部证据的部分留待核实，不把整卡退成待填写占位。原文未给时不编造逐字引文。关系、因果和解释深度可以充分设计，不能用“数据未提供”省略知识要求。
尊重宿主尺寸与能力，不把实现说明写给用户。原生优先，允许Web才为高阶动画/复杂逻辑建议局部增强，不默认整卡重写；关闭Web不静默删目标，工具关闭不承诺实时查询或以mock冒充。未提供条件可编辑/待填写，不猜日期，本地教学计算可有明确示例初值。完整长页只放宽容器高度，不将用户短卡扩写为全文图鉴或新增必需CUJ；当前对象的详情仍随选择切换，补充资料可进入具名目的地。方形按需展开不能裁切主要操作。图片先行仅设置启用或用户要求时使用。
验收融入各CUJ的可见结果，不另抄通用工程清单、不指定测试定位器、固定样本数量或未取得的事实预期。保留相关专业风险与不确定性，不堆免责声明。
最后做范围检查：简单计算器只规划录入/修改→结果与可核对依据；未明确要求的多种输入制式、换算规则编辑器、设置面板一律不加，不借“必要依赖”扩大范围。用户只给单一目标时，简短两条CUJ优先于四段模板。复杂目标则确保每项原始要求都有CUJ或内容位置，去掉重复与人为解锁门槛。`

export function refineContext(payload={}){
 const size=normalizeCardSize(payload.cardSize),settings=generationSettings(payload)
 return {
  request:payload.prompt,
  contentOrganization:readingInstruction(settings.contentMode)||'连续阅读，保持相同信息预算',
  layout:settings.contentMode?'手机320–432px，空间与信息层级分开；按contentOrganization设计具名详情目的地，不要求全部内容连续展开。':size==='full'?'完整长页：内容自然延展但保留用户短卡意图；主体与当前选择详情相邻，补充资料按需可达，不要求全部对象的正文重复展开。':size==='auto'?'自然高度：手机一屏高度附近，紧凑主体与按需详情，不因高度增加正文。':'方形320–432px：一个主体和主要操作，设置/详情按需打开，不靠缩小文字塞满。',
  capabilities:{graphics:payload.renderMode==='web'&&payload.webGraphics===true?'允许Canvas/WebGL/WebGPU与shader，视觉需有操作价值；设备失败时简化显示':'Canvas/SVG/CSS表达，不规划GPU shader',format:payload.format==='dil'?'DIL':'CardSpec',web:payload.renderMode==='web'?'独立Web表达可用':payload.renderMode==='hybrid'?'原生为主，可嵌Web增强':'仅原生；不建议Web沙箱',tools:payload.toolsEnabled===false?'关闭：不能承诺实时查询；所需数据待用户提供或启用工具':'已启用：生成阶段发现CLI、真实取数并绑定到卡片，来源是否成功以执行为准；不能把此需求降为静态框架'},
  design:{family:settings.designPreference||'auto',process:settings.designMode==='image-first'?'图片先行已选，后续按设计参考实现真实交互':'宿主成熟构图优先，不新增图片先行步骤'},
 }
}
