test('sandbox theme bridge carries motion settings including pseudo elements',async({page})=>{
 await page.goto('/cardspec-lab.html?fixture=counter')
 await page.evaluate(async()=>{
  const {sandboxDocument}=await import('/src/cardspec/sandbox-document.mjs')
  const iframe=document.createElement('iframe');iframe.id='motion-frame';iframe.sandbox='allow-scripts';iframe.srcdoc=sandboxDocument('@keyframes orbit{to{transform:rotate(360deg)}}#root .orbit::before{content:"";display:block;width:20px;height:20px;background:red;animation:orbit 2s linear infinite!important}','motion-test');document.body.append(iframe)
  await new Promise(r=>iframe.onload=r)
  iframe.contentWindow.postMessage({sandbox:'motion-test',type:'render',revision:1,tree:{type:'div',props:{className:'orbit'},children:[]}},'*')
  iframe.contentWindow.postMessage({sandbox:'motion-test',type:'environment',active:true,motionLevel:'full',theme:{'--cs-motion-duration':'280ms'}},'*')
 })
 const orbit=page.frameLocator('#motion-frame').locator('.orbit')
 await expect.poll(()=>orbit.evaluate(el=>getComputedStyle(el,'::before').animationPlayState)).toBe('running')
 await page.evaluate(()=>document.querySelector('#motion-frame').contentWindow.postMessage({sandbox:'motion-test',type:'environment',active:false,motionLevel:'light'},'*'))
 await expect.poll(()=>orbit.evaluate(el=>getComputedStyle(el,'::before').animationPlayState)).toBe('paused')
 await page.evaluate(()=>document.querySelector('#motion-frame').contentWindow.postMessage({sandbox:'motion-test',type:'environment',active:false,motionLevel:'off'},'*'))
 await expect.poll(()=>orbit.evaluate(el=>getComputedStyle(el,'::before').animationName)).toBe('none')
})
