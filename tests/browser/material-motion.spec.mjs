const out='artifacts/material-motion-qa';mkdirSync(out,{recursive:true})
const photoFile=readdirSync('.cache/pexels').find(f=>f.endsWith('.jpg'))
const photos=readdirSync('.cache/pexels').filter(f=>f.endsWith('.json')).flatMap(f=>{try{const p=JSON.parse(readFileSync('.cache/pexels/'+f,'utf8')).photo;return p?.content&&existsSync('.cache/pexels/'+p.content.split('/').pop())?[p]:[]}catch{return []}})
const chosen={lake:photos.find(p=>/lake/i.test(p.title)),forest:photos.find(p=>/forest.*path|path.*forest|forest/i.test(p.title)),mountain:photos.find(p=>/mountain/i.test(p.title))}
