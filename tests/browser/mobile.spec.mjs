test('bar and line charts expose negative/zero values and selectable data', async({page})=>{
  await lab(page,'chart')
  await page.getByRole('button',{name:'周二 -10元',exact:true}).tap()
  await expect(page.locator('.cs-card')).toContainText('tue：-10元')
  await expect(page.getByRole('button',{name:'周三 0元',exact:true})).toBeVisible()
  const rects=await page.locator('.cs-chart-mark rect').evaluateAll(els=>els.map(el=>Number(el.getAttribute('height'))))
  expect(rects.every(h=>Number.isFinite(h)&&h>=1)).toBe(true)
  await page.getByText('输入 DSL 验证',{exact:true}).click()
  await page.getByLabel('DSL源码').fill(MOBILE_FIXTURES.chart.replace('kind="bar"','kind="line"'))
  await page.getByRole('button',{name:'应用源码'}).click()
  await expect(page.locator('.cs-chart polyline')).toHaveCount(1)
  await expect(page.locator('.cs-chart-mark circle')).toHaveCount(4)
  await page.getByRole('button',{name:'周四 35元',exact:true}).click()
  await expect(page.locator('.cs-card')).toContainText('thu：35元')
})
test('hero and each-item thumbnails reserve correct space with different sources', async({page})=>{
  await lab(page,'media')
  const images=page.locator('.cs-image img')
  await expect(images).toHaveCount(3)
  expect(new Set(await images.evaluateAll(els=>els.map(el=>el.src))).size).toBe(3)
  expect((await page.locator('.cs-image[data-media-role=hero]').boundingBox()).height).toBeGreaterThanOrEqual(112)
  expect((await page.locator('.cs-image[data-media-role=thumbnail]').first().boundingBox()).height).toBe(64)
  await page.getByLabel('图片',{exact:true}).selectOption('error')
  await expect(page.locator('.cs-image').first()).toContainText('图片暂不可用')
})
