import { test,expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
mkdirSync('artifacts/capabilities-qa/screenshots',{recursive:true})
async function lab(page,name,width='320') {
  await page.goto(`/cardspec-lab.html?fixture=${name}`)
  await page.getByLabel('宽度',{exact:true}).selectOption(width)
  await expect(page.getByTestId('diagnostics')).toHaveText('[]')
  await expect(page.locator('[data-cs-error]')).toHaveCount(0)
}
test('select, radio and segmented share values, keep keyboard operation and animated thumb',async({page})=>{
  await lab(page,'choices')
  const card=page.locator('.cs-card'), track=card.locator('.cs-segmented'), thumb=track.locator('.cs-segmented-thumb')
  const before=await thumb.evaluate(el=>el.style.transform)
  await track.getByRole('radio',{name:'下午',exact:true}).click()
  await expect(card.getByLabel('下拉时段')).toHaveValue('下午')
  await expect(card.getByRole('radio',{name:'下午：处理协作与沟通'})).toBeChecked()
  expect(await thumb.evaluate(el=>el.style.transform)).not.toBe(before)
  await card.getByLabel('下拉时段').selectOption('晚上')
  await expect(track.getByRole('radio',{name:'晚上',exact:true})).toHaveAttribute('aria-checked','true')
  await track.getByRole('radio',{name:'晚上',exact:true}).press('Home')
  await expect(card.getByLabel('下拉时段')).toHaveValue('上午')
  await page.locator('.cs-stage').screenshot({path:'artifacts/capabilities-qa/screenshots/choices.png'})
})
