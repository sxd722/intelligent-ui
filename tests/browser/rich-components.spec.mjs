test('swipe choices fire once, support dragging, fixed height and restart',async({page})=>{
  await lab(page,'swipe')
  const card=page.locator('.cs-card'), deck=card.locator('.cs-swipe-deck'),height=(await deck.boundingBox()).height
  await expect(card.locator('.cs-confetti')).toHaveCount(0)
  await card.getByRole('button',{name:'收藏',exact:true}).click()
  await expect(card).toContainText('收藏 1 项')
  await expect(card.locator('.cs-confetti')).toHaveCount(1)
  const r=await deck.boundingBox();await page.mouse.move(r.x+r.width*.75,r.y+40);await page.mouse.down();await page.mouse.move(r.x+10,r.y+42,{steps:8});await page.mouse.up()
  await expect(card).toContainText('3 / 3');expect((await deck.boundingBox()).height).toBe(height)
  await card.getByRole('button',{name:'收藏',exact:true}).click();await expect(card).toContainText('已浏览全部卡片');await expect(card).toContainText('收藏 2 项')
  await expect(card.getByRole('button',{name:'收藏',exact:true})).toBeDisabled()
  await card.getByRole('button',{name:'重新开始',exact:true}).click();await expect(card).toContainText('1 / 3')
  await expect(card.locator('.cs-confetti')).toHaveCount(0)
  await page.locator('.cs-stage').screenshot({path:'artifacts/capabilities-qa/screenshots/swipe.png'})
})
for(const kind of ['flow','sequence','state','class','er','xy'])test(`Mermaid ${kind}: SVG, fit, scoped markers, selection and expansion`,async({page})=>{
  await lab(page,`mermaid-${kind}`)
  await expect(page.locator('.cs-mermaid-svg svg')).toHaveCount(1)
  await expect(page.locator('[data-cs-error]')).toHaveCount(0)
  await expect(page.locator('.cs-stage')).toHaveAttribute('data-cs-fit','fit')
  const svg=page.locator('.cs-mermaid-svg svg')
  expect(await svg.locator('script,foreignObject,style').count()).toBe(0)
  await expect.poll(()=>svg.evaluate(el=>{const p=el.closest('.cs-mermaid-pan');return el.getBoundingClientRect().width<=p.clientWidth+1&&p.scrollHeight<=p.clientHeight+1})).toBe(true)
  if(kind!=='xy') {
    const node=svg.getByRole('button').first();await node.click();await expect(node).toHaveAttribute('aria-pressed','true')
    await node.press('Enter');await expect(page.locator('.cs-widget-caption')).toContainText('已选择')
  }
  await page.getByRole('button',{name:'放大图形'}).click();await expect(page.getByRole('button',{name:'图形全貌'})).toHaveText('125%')
  await page.getByRole('button',{name:'图形全貌'}).click()
  await page.locator('.cs-stage').screenshot({path:`artifacts/capabilities-qa/screenshots/mermaid-${kind}.png`})
  await page.getByRole('button',{name:'展开图形'}).click();await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').locator('svg')).toHaveCount(1)
  await page.getByRole('button',{name:'收起图形'}).click();await expect(page.getByRole('dialog')).not.toBeVisible()
})
