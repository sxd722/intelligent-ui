import { test,expect } from '@playwright/test'

test('long reading: idle fade, native keyboard scrolling, edge hints and stable geometry',async({page})=>{
  await page.goto('/cardspec-lab.html?fixture=longtext')
  const body=page.locator('.cs-region-body').last()
  await expect(body).toHaveAttribute('data-scroll-y','true')
  await expect(body).toHaveAttribute('data-scroll-top-more','false')
  await expect(body).toHaveAttribute('data-scroll-bottom-more','true')
  const width=await body.evaluate(el=>el.clientWidth)
  await page.mouse.move(0,0)
  await expect(body).toHaveAttribute('data-scroll-active','false')
  await expect.poll(()=>body.evaluate(el=>getComputedStyle(el).scrollbarColor)).toBe('rgba(0, 0, 0, 0) rgba(0, 0, 0, 0)')
  await body.hover()
  await expect.poll(()=>body.evaluate(el=>getComputedStyle(el).scrollbarColor)).not.toBe('rgba(0, 0, 0, 0) rgba(0, 0, 0, 0)')
  expect(await body.evaluate(el=>el.clientWidth)).toBe(width)
  await body.focus();await body.press('End')
  await expect(body).toHaveAttribute('data-scroll-top-more','true')
  await expect(body).toHaveAttribute('data-scroll-bottom-more','false')
  await expect(body).toHaveAttribute('data-scroll-active','true')
  await body.press('Home')
  await expect(body).toHaveAttribute('data-scroll-top-more','false')
  await expect(body).toHaveAttribute('data-scroll-bottom-more','true')
  await page.emulateMedia({forcedColors:'active',reducedMotion:'reduce'})
  expect(await body.evaluate(el=>({mask:getComputedStyle(el).maskImage,color:getComputedStyle(el).scrollbarColor,transition:getComputedStyle(el).transitionDuration}))).toEqual({mask:'none',color:'auto',transition:'0s'})
})

test('horizontal carousel reveals remaining direction without vertical overflow',async({page})=>{
  await page.goto('/cardspec-lab.html?fixture=carousel')
  const track=page.locator('.cs-carousel-track')
  await expect(track).toHaveAttribute('data-scroll-x','true')
  await expect(track).toHaveAttribute('data-scroll-y','false')
  await expect(track).toHaveAttribute('data-scroll-left-more','false')
  await expect(track).toHaveAttribute('data-scroll-right-more','true')
  await page.getByRole('button',{name:'下一项',exact:true}).click()
  await expect(page.locator('.cs-carousel')).toHaveAttribute('data-active-index','1')
  await page.getByRole('button',{name:'下一项',exact:true}).click()
  await expect(page.locator('.cs-carousel')).toHaveAttribute('data-active-index','2')
  await expect(track).toHaveAttribute('data-scroll-left-more','true')
  await expect(track).toHaveAttribute('data-scroll-right-more','false')
})

test('diagram zoom and reset update overflow hints; fitting content has no fade',async({page})=>{
  await page.goto('/cardspec-lab.html?fixture=mermaid-flow')
  const pan=page.locator('.cs-mermaid-pan').first()
  await expect(page.locator('.cs-mermaid-svg svg')).toHaveCount(1)
  await expect(pan).toHaveAttribute('data-scroll-y','false')
  await expect(pan).toHaveAttribute('data-scroll-x','false')
  for(let i=0;i<4;i++)await page.getByRole('button',{name:'放大图形'}).click()
  await expect.poll(()=>pan.evaluate(el=>el.dataset.scrollY==='true'||el.dataset.scrollX==='true')).toBe(true)
  await page.getByRole('button',{name:'图形全貌'}).click()
  await expect(pan).toHaveAttribute('data-scroll-y','false')
  await expect(pan).toHaveAttribute('data-scroll-x','false')
  expect(await pan.evaluate(el=>getComputedStyle(el).maskImage)).toBe('none')
})
